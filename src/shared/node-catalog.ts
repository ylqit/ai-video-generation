export const nodeTypes = nodeDefinitions.map((d) => d.type) as [string, ...string[]];
export function nodeMediaType(type: string): 'image' | 'video' | 'audio' | undefined {
  if (['image', 'image_generate'].includes(type)) return 'image';
  if (['video', 'video_generate', 'lipsync', 'director'].includes(type)) return 'video';
  if (['audio', 'audio_generate'].includes(type)) return 'audio';
}
